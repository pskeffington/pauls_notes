# Synthetic numerical checks for foundations lab.
args <- commandArgs(trailingOnly=FALSE)
file_arg <- grep("^--file=", args, value=TRUE)
if (!length(file_arg)) stop("Execute via Rscript --vanilla.")
here <- dirname(normalizePath(sub("^--file=","",file_arg[1L]),mustWork=TRUE))
source(file.path(here,"..","examples","breast_cancer_foundations_lab.R"))
set.seed(992L); before_state <- get(".Random.seed",envir=.GlobalEnv)
r <- breast_cancer_foundations_lab(simulations=500L)
stopifnot(identical(get(".Random.seed",envir=.GlobalEnv),before_state))
near <- function(actual,target,tol=1e-6)
  stopifnot(isTRUE(all.equal(as.numeric(actual),target,tolerance=tol)))
near(r$descriptive["mean"],12)
near(r$descriptive["variance"],48/7)
near(r$descriptive["se"],sqrt(48/7)/sqrt(8))
near(r$clt$theoretical_se_n5,10/sqrt(5))
near(r$clt$theoretical_se_n50,10/sqrt(50))
stopifnot(length(r$clt$means_n5)==500L,length(r$clt$means_n50)==500L,
          identical(r$clt$means_n5,
                    breast_cancer_foundations_lab(500L)$clt$means_n5))
near(r$welch$estimate[1L]-r$welch$estimate[2L],-3.5)
near(r$welch$statistic,-2.04939015319192)
near(r$welch$parameter,7.352941176470588)
near(unname(r$paired$estimate),-1.625)
near(r$anova_components$F_value,3)
near(unname(summary(r$anova)[[1L]][["F value"]][1L]),3)
near(stats::pf(3,2,6,lower.tail=FALSE),.125)
near(r$binomial_tail,
     sum(stats::dbinom(36:80,80,.35)),tol=1e-12)
near(r$binomial$p.value,r$binomial_tail,tol=1e-12)
near(r$poisson_tail,stats::ppois(9,8,lower.tail=FALSE),tol=1e-12)
stopifnot(inherits(r$pooled_student,"htest"),inherits(r$welch_anova,"htest"))
cat("PASS: synthetic foundations formulas, CLT reproducibility, mean contrasts, ANOVA, binomial and Poisson.\\n")
